// Release signing: keystore.properties (local) or GARASI_* env vars (CI).
// If neither is present the release build falls back to the debug key so
// `assembleRelease` always produces an installable APK.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(prop: String, env: String): String? =
    keystoreProps.getProperty(prop) ?: System.getenv(env)?.takeIf { it.isNotBlank() }

val releaseStoreFile = signingValue("storeFile", "GARASI_KEYSTORE_PATH")
val hasReleaseKey = releaseStoreFile != null && rootProject.file(releaseStoreFile).exists()

